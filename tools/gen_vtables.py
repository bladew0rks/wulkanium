"""generate src/vtables.rs from layout/gmod_x64_vtables.json.

per interface: slot constants, slot names and a logging stub per slot that returns a zero of the
right kind for the msvc x64 abi. run from the crate root: python3 tools/gen_vtables.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
layout = json.load(open(os.path.join(CRATE, 'layout', 'gmod_x64_vtables.json')))

MODS = {
    'IShaderAPI': 'shader_api',
    'IShaderShadow': 'shader_shadow',
    'IShaderDevice': 'shader_device',
    'IShaderDeviceMgr': 'shader_device_mgr',
    'IHardwareConfigInternal': 'hardware_config',
    'IDebugTextureInfo': 'debug_texture_info',
    'IMesh': 'mesh',
    'IMesh@IIndexBuffer': 'mesh_index_buffer',
    'IVertexBuffer': 'vertex_buffer',
    'IIndexBuffer': 'index_buffer',
}

def ret_type(slot):
    sig, name = slot['sig'], slot['name']
    return re.sub(r'^virtual\s+', '', sig[:sig.index(name)]).strip()

def kind(slot):
    r = ret_type(slot)
    if slot['name'].startswith('~'):
        return 'dtor'
    if r == 'float':
        return 'f32'
    if r == 'double':
        return 'f64'
    if r == 'Vector':
        return 'vector'
    if r.endswith('&'):
        return 'ref'
    return 'int'

out = ['// @generated by tools/gen_vtables.py, do not edit',
       '#![allow(non_upper_case_globals, clippy::all)]',
       'use std::ffi::c_void;', '',
       'pub const IFACE_NAMES: [&str; %d] = [%s];' % (len(MODS), ', '.join(f'"{k}"' for k in MODS)), '']
for idx, (iface, mod) in enumerate(MODS.items()):
    slots = layout[iface]['slots']
    seen = {}
    consts = []
    for s in slots:
        n = s['name'].replace('~', 'Destructor_')
        k = seen.get(n, 0); seen[n] = k + 1
        consts.append(n if k == 0 else f'{n}_{k}')
    out.append(f'/// `{iface}`, {len(slots)} slots')
    out.append(f'pub mod {mod} {{')
    out.append('    use super::*;')
    out.append(f'    pub const IFACE: u8 = {idx};')
    out.append(f'    pub const LEN: usize = {len(slots)};')
    out.append('    pub const NAMES: [&str; LEN] = [' + ', '.join(f'"{c}"' for c in consts) + '];')
    out.append('    /// overloads get `_1`, `_2`, ... in vtable order')
    out.append('    pub mod slot {')
    for i, c in enumerate(consts):
        out.append(f'        pub const {c}: usize = {i};')
    out.append('    }')
    for i, s in enumerate(slots):
        k = kind(s)
        log = f'crate::log::stub(IFACE, {i})'
        if k == 'int':
            out.append(f'    unsafe extern "C" fn s{i}(_this: *mut c_void) -> usize {{ {log}; 0 }}')
        elif k == 'f32':
            out.append(f'    unsafe extern "C" fn s{i}(_this: *mut c_void) -> f32 {{ {log}; 0.0 }}')
        elif k == 'f64':
            out.append(f'    unsafe extern "C" fn s{i}(_this: *mut c_void) -> f64 {{ {log}; 0.0 }}')
        elif k == 'dtor':
            out.append(f'    unsafe extern "C" fn s{i}(this: *mut c_void) -> *mut c_void {{ {log}; this }}')
        elif k == 'ref':
            out.append(f'    unsafe extern "C" fn s{i}(_this: *mut c_void) -> *const u8 {{ {log}; crate::log::ZEROES.0.as_ptr() }}')
        elif k == 'vector':
            out.append(f'    unsafe extern "C" fn s{i}(_this: *mut c_void, ret: *mut [f32; 3]) -> *mut [f32; 3] {{ {log}; unsafe {{ *ret = [0.0; 3] }}; ret }}')
    out.append('    pub fn stubs() -> [usize; LEN] {')
    out.append('        [' + ', '.join(f's{i} as *const () as usize' for i in range(len(slots))) + ']')
    out.append('    }')
    out.append('}')
    out.append('')
out.append('pub fn slot_names(iface: u8) -> &\'static [&\'static str] {')
out.append('    match iface {')
for idx, mod in enumerate(MODS.values()):
    out.append(f'        {idx} => &{mod}::NAMES,')
out.append('        _ => &[],')
out.append('    }')
out.append('}')
open(os.path.join(CRATE, 'src', 'vtables.rs'), 'w').write('\n'.join(out) + '\n')
print('wrote src/vtables.rs:', ', '.join(f'{k} {len(layout[k]["slots"])}' for k in MODS))
